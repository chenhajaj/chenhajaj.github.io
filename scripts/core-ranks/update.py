"""Rebuild _data/core_ranks.yml from the CORE / ICORE conference portal.

Each venue Chen publishes in is matched by acronym and a phrase from its
CORE title. The site shows, for each conference paper, the rank in the CORE
edition in force when the paper appeared (Chen's choice, Oct 2026).

Run:  python3 scripts/core-ranks/update.py   (needs network access)
"""
import csv, io, pathlib, urllib.request

EDITIONS = {"CORE2013": 2013, "CORE2014": 2014, "CORE2017": 2017, "CORE2018": 2018,
            "CORE2020": 2020, "CORE2021": 2021, "CORE2023": 2023, "ICORE2026": 2026}
# match: text found in the venue name in papers.bib -> (CORE acronym, phrase in CORE title)
VENUES = [
    ("Human Computation and Crowdsourcing", "HCOMP", "Human Computation"),
    ("AAAI Conference on Artificial Intelligence", "AAAI", "Artificial Intelligence"),
    ("Joint Conference on Artificial Intelligence", "IJCAI", "Joint Conference"),
    ("Autonomous Agents and Multiagent Systems", "AAMAS", "Autonomous Agents"),
    ("Economics and Computation", "EC", "Economics and Computation"),
    ("USENIX Security", "USENIX-Security", "Security"),
    ("INFOCOM", "INFOCOM", "Computer Communications"),
    ("Interspeech", "Interspeech", "Interspeech"),
    ("Consumer Communications", "IEEE CCNC", "Consumer Communications"),
    ("International Conference on Communications (ICC)", "ICC", "International Conference on Communications"),
    ("International Conference on Information Systems (ICIS)", "ICIS", "International Conference on Information Systems"),
    ("Frontiers in Education", "FIE", "Frontiers in Education"),
    ("FedCSIS", "FedCSIS", "Intelligence Systems"),
    ("CAADRIA", "CAADRIA", "Architectural Design"),
]
RANKS = {"A*", "A", "B", "C"}

def fetch(src):
    url = f"https://portal.core.edu.au/conf-ranks/?search=&by=all&source={src}&sort=arank&page=1&do=Export"
    return list(csv.reader(io.StringIO(urllib.request.urlopen(url, timeout=60).read().decode("utf-8", "replace"))))

tables = {src: fetch(src) for src in EDITIONS}
out = ["# CORE conference ranks by edition. Generated by scripts/core-ranks/update.py; do not edit by hand.",
       "# Source: ICORE portal (portal.core.edu.au). Only A*, A, B and C are kept.", "editions: [" +
       ", ".join(str(y) for y in EDITIONS.values()) + "]", "venues:"]
for match, acr, phrase in VENUES:
    ranks = {}
    for src, year in EDITIONS.items():
        for row in tables[src]:
            if len(row) > 4 and row[2].strip() == acr and phrase.lower() in row[1].lower() and row[4].strip() in RANKS:
                ranks[year] = row[4].strip()
                break
    out.append(f'  - match: "{match}"')
    out.append(f'    acronym: "{acr}"')
    out.append("    ranks: {" + ", ".join(f'{y}: "{r}"' for y, r in ranks.items()) + "}")
root = pathlib.Path(__file__).resolve().parents[2]
(root / "_data/core_ranks.yml").write_text("\n".join(out) + "\n")
print("\n".join(out))
