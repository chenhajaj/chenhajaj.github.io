"""Rebuild _data/sjr_quartiles.yml: SJR best quartile per journal and year.

Source: SCImago Journal Rank, via the open sjrdata package
(github.com/ikashnitsky/sjrdata, which pools the scimagojr.com downloads).
The site shows, for each journal paper, the journal's best SJR quartile in the
year the paper appeared (the latest SJR year for newer papers).

Run after `bundle exec jekyll build` (it reads the journal list from the built
research data):
  GIT_LFS_SKIP_SMUDGE=1 git clone --depth 1 https://github.com/ikashnitsky/sjrdata /tmp/sjrdata
  python3 scripts/sjr/update.py /tmp/sjrdata/data-raw/sjr-journal/sjr_journals-2026.parquet
Needs pandas and pyarrow.
"""
import json, pathlib, re, sys

import pandas as pd

root = pathlib.Path(__file__).resolve().parents[2]
src = sys.argv[1]
norm = lambda t: re.sub(r"[^a-z0-9]", "", str(t).lower().replace("&", "and"))

# Journals whose name is shared by other journals in SJR: pin them by ISSN.
ISSN = {"Electronics": "20799292"}  # MDPI Electronics, not "Electronics" (Banja Luka)

research = json.loads((root / "_site/assets/data/research.json").read_text())
journals = sorted({p["venue"] for p in research["papers"] if p["kind"] == "journal" and p["venue"]})

d = pd.read_parquet(src, columns=["year", "title", "issn", "type", "sjr_best_quartile"])
d = d[(d["type"] == "journal") & d["sjr_best_quartile"].isin(["Q1", "Q2", "Q3", "Q4"])]
d["n"] = d["title"].map(norm)
latest = int(d["year"].max())

out = [
    "# SJR best quartile per journal and year. Generated by scripts/sjr/update.py; do not edit by hand.",
    "# Source: SCImago Journal Rank (scimagojr.com) via github.com/ikashnitsky/sjrdata.",
    f"latest_year: {latest}",
    "journals:",
]
missing = []
for j in journals:
    if j in ISSN:
        rows = d[d["issn"].str.contains(ISSN[j], na=False)]
    else:
        rows = d[d["n"] == norm(j)]
        if rows["issn"].nunique() > 1:  # same name, different journals
            sys.exit(f"ambiguous journal name {j!r}: ISSNs {sorted(rows['issn'].unique())}; add it to ISSN")
    rows = rows.sort_values("year")
    if rows.empty:
        missing.append(j)
        continue
    q = ", ".join(f'{int(y)}: "{v}"' for y, v in zip(rows["year"], rows["sjr_best_quartile"]) if y >= 2010)
    out.append(f"  - match: {json.dumps(j)}")
    out.append("    quartiles: {" + q + "}")
(root / "_data/sjr_quartiles.yml").write_text("\n".join(out) + "\n")
print(f"{len(journals) - len(missing)} journals written, SJR up to {latest}")
if missing:
    print("not in SJR:", "; ".join(missing))
